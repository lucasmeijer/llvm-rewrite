#!/usr/bin/env python3
"""Generates src/gen_triple.jai from llvm/include/llvm/TargetParser/TripleName.def: the Triple OS, environment and
vendor enums, their canonical names (getOSTypeName / getEnvironmentTypeName / getVendorTypeName) and the parse
tables in the .def's order (parseOS / parseEnvironment match prefixes in that order, parseVendor whole names).

Usage: python3 impl/jai/gen/gen_triple.py > impl/jai/src/gen_triple.jai
"""
import re

D = open('/opt/llvm-project-23.1.5/llvm/include/llvm/TargetParser/TripleName.def').read()
D = re.sub(r'//[^\n]*', '', D)


def table(kind):
    canon, parse = [], []
    for m in re.finditer(r'^TRIPLE_%s(_ALIAS)?\((\w+),\s*"([^"]*)"\)' % kind, D, re.M):
        alias, enum, name = m.group(1), m.group(2), m.group(3)
        if not alias:
            canon.append((enum, name))
        parse.append((enum, name))
    return canon, parse


out = ['// GENERATED by impl/jai/gen/gen_triple.py from llvm/include/llvm/TargetParser/TripleName.def. Do not edit.', '']
for kind, ty, unk in (('OS', 'Triple_OS', 'UnknownOS'), ('ENV', 'Triple_Env', 'UnknownEnvironment'),
                      ('VENDOR', 'Triple_Vendor', 'UnknownVendor')):
    canon, parse = table(kind)
    out.append('%s :: enum u8 {' % ty)
    out.append('    %s :: 0;' % unk)
    for e, _ in canon:
        out.append('    %s;' % e)
    out.append('}')
    out.append('%s_NAMES :: string.[' % ty.upper())
    out.append('    "unknown",')
    for _, n in canon:
        out.append('    "%s",' % n)
    out.append('];')
    out.append('%s_PARSE :: struct { name: string; v: %s; }.[' % (ty.upper(), ty))
    for e, n in parse:
        out.append('    .{"%s", .%s},' % (n, e))
    out.append('];')
    out.append('')
print('\n'.join(out))
