#!/usr/bin/env python3
"""Generates src/gen_cc.jai: calling-convention keywords <-> numbers.
Numbers from llvm/include/llvm/IR/CallingConv.h, parse keywords from LLParser::parseOptionalCallingConv,
print names from AsmWriter.cpp printCallingConv."""
import re
L = '/opt/llvm-project-23.1.5/llvm/'
nums = dict(re.findall(r'^\s+([A-Za-z_0-9]+) = (\d+),', open(L + 'include/llvm/IR/CallingConv.h').read(), re.M))
parse = re.findall(r'case lltok::kw_([a-z_0-9]+):\s*CC = CallingConv::([A-Za-z_0-9]+);', open(L + 'lib/AsmParser/LLParser.cpp').read())
aw = open(L + 'lib/IR/AsmWriter.cpp').read()
prt = re.findall(r'case CallingConv::([A-Za-z_0-9]+):\s*Out << "([^"]+)";', aw)
prt += re.findall(r'case CallingConv::([A-Za-z_0-9]+):\s*\n\s*Out << "([^"]+)";', aw)
print('// GENERATED by impl/jai/gen/gen_cc.py. Do not edit.')
print('CC_Name :: struct { num: u32; name: string; }')
print('CC_PARSE :: CC_Name.[')
for kw, e in parse:
    print('    .{%s, "%s"},' % (nums[e], kw))
print('];')
print('CC_PRINT :: CC_Name.[')
for e, name in prt:
    print('    .{%s, "%s"},' % (nums[e], name))
print('];')
