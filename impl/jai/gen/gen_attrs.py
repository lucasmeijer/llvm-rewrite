#!/usr/bin/env python3
"""Generates src/gen_attrs.jai from LLVM's llvm/include/llvm/IR/Attributes.td.

The attribute-kind enum must follow tablegen's order (Attribute::AttrKind): EnumAttr records sorted by record
name, then TypeAttr, IntAttr, ConstantRangeAttr, ConstantRangeListAttr. AttributeSet sorting depends on it.
Run: python3 impl/jai/gen/gen_attrs.py > impl/jai/src/gen_attrs.jai
"""
import re, sys
TD = '/opt/llvm-project-23.1.5/llvm/include/llvm/IR/Attributes.td'
src = open(TD).read()
# join "def X\n    : EnumAttr<..." forms
defs = re.findall(r'^def\s+([A-Za-z0-9_]+)\s*:\s*(EnumAttr|TypeAttr|IntAttr|ConstantRangeAttr|ConstantRangeListAttr)<"([^"]+)"', src, re.M)
order = ['EnumAttr', 'TypeAttr', 'IntAttr', 'ConstantRangeAttr', 'ConstantRangeListAttr']
out = []
out.append('// GENERATED by impl/jai/gen/gen_attrs.py from llvm/include/llvm/IR/Attributes.td. Do not edit.\n')
out.append('Attr_Kind :: enum u8 {\n    NONE_ATTR;\n')
names = []
for o in order:
    recs = sorted([d for d in defs if d[1] == o], key=lambda d: d[0])
    for r in recs:
        out.append('    %s;\n' % r[0])
        names.append((r[0], r[2]))
    out.append('    LAST_%s;\n' % {'EnumAttr':'ENUM','TypeAttr':'TYPE','IntAttr':'INT','ConstantRangeAttr':'RANGE','ConstantRangeListAttr':'RANGELIST'}[o])
out.append('    STRING_ATTR;\n}\n\n')
out.append('ATTR_NAMES :: Attr_Name.[\n')
for rec, name in names:
    out.append('    .{.%s, "%s"},\n' % (rec, name))
out.append('];\n\nAttr_Name :: struct { kind: Attr_Kind; name: string; }\n')
sys.stdout.write(''.join(out))
