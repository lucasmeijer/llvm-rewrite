#!/usr/bin/env python3
"""Generates src/gen_tli.jai from llvm/include/llvm/Analysis/TargetLibraryInfo{,Impl}.td, like
llvm/utils/TableGen/Basic/TargetLibraryInfoEmitter.cpp does for TargetLibraryInfo.inc:

- `Lib_Func`: the LibFunc enum (NotLibFunc = 0, then every TargetLibCall def in input order, then NumLibFuncs).
  Member names are the def names; a def name that is a Jai keyword gets a trailing `_` (`remove_`).
- `Func_Arg_Type`: the FuncArgTypeID enum (NoFuncArgType = 0, then the FuncArgType defs in input order).
- `LIB_FUNC_NAMES`: StandardNames, indexed by Lib_Func.
- `LIB_FUNC_SIG_OFFSET` / `LIB_FUNC_SIG`: each function's signature (return type, then argument types),
  terminated by NoFuncArgType (the emitter's SequenceToOffsetTable shares suffixes; we don't, which doesn't
  change any lookup).

Usage: python3 impl/jai/gen/gen_tli.py > impl/jai/src/gen_tli.jai
"""
import re

L = '/opt/llvm-project-23.1.5/llvm/include/llvm/Analysis/'
JAI_KEYWORDS = {'remove', 'if', 'else', 'for', 'while', 'case', 'return', 'struct', 'enum', 'defer', 'cast', 'it',
                'null', 'true', 'false', 'using', 'inline', 'break', 'continue', 'xx', 'union', 'then', 'ifx'}


def strip_comments(s):
    return re.sub(r'/\*.*?\*/', '', re.sub(r'//[^\n]*', '', s), flags=re.S)


impl = strip_comments(open(L + 'TargetLibraryInfoImpl.td').read())
arg_types = re.findall(r'^def\s+([A-Za-z_0-9]+)\s*:\s*FuncArgType\s*;', impl, re.M)

td = strip_comments(open(L + 'TargetLibraryInfo.td').read())
defs = []
for m in re.finditer(r'def\s+([A-Za-z_0-9]+)\s*:\s*TargetLibCall\s*<\s*"([^"]*)"\s*,\s*([A-Za-z_0-9]+|\?)\s*(?:,\s*\[([^\]]*)\])?\s*>\s*;', td, re.S):
    name, string, ret, args = m.group(1), m.group(2), m.group(3), m.group(4)
    args = [a.strip() for a in args.split(',')] if args and args.strip() else []
    defs.append((name, string, ret, args))
assert len(defs) == td.count('TargetLibCall<'), (len(defs), td.count('TargetLibCall<'))
for _, _, r, a in defs:
    for t in ([r] if r != '?' else []) + a:
        assert t in arg_types, t


def member(n):
    return n + '_' if n in JAI_KEYWORDS else n


out = []
out.append('// GENERATED by impl/jai/gen/gen_tli.py from llvm/include/llvm/Analysis/TargetLibraryInfo.td. Do not edit.')
out.append('')
out.append('Lib_Func :: enum u16 {')
out.append('    NotLibFunc :: 0;')
for n, _, _, _ in defs:
    out.append('    %s;' % member(n))
out.append('    NumLibFuncs;')
out.append('}')
out.append('NUM_LIB_FUNCS :: %d;' % (len(defs) + 1))
out.append('')
out.append('Func_Arg_Type :: enum u8 {')
out.append('    NoFuncArgType :: 0;')
for t in arg_types:
    out.append('    %s;' % t)
out.append('}')
out.append('')
out.append('LIB_FUNC_NAMES :: string.[')
out.append('    "",')
for _, s, _, _ in defs:
    out.append('    "%s",' % s.replace('\\', '\\\\'))
out.append('];')
out.append('')
sig = ['Void', 'NoFuncArgType']   # NotLibFunc's signature
offsets = [0]
for _, _, r, a in defs:
    offsets.append(len(sig))
    # an unset return type (`?`, "checked manually" in isValidProtoForLibFunc) gives an empty signature
    sig += ([r] if r != '?' else []) + a + ['NoFuncArgType']
out.append('LIB_FUNC_SIG_OFFSET :: u16.[')
for i in range(0, len(offsets), 16):
    out.append('    ' + ', '.join(str(o) for o in offsets[i:i + 16]) + ',')
out.append('];')
out.append('LIB_FUNC_SIG :: Func_Arg_Type.[')
for i in range(0, len(sig), 12):
    out.append('    ' + ', '.join('.' + t for t in sig[i:i + 12]) + ',')
out.append('];')
print('\n'.join(out))
