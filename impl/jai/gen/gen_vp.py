#!/usr/bin/env python3
"""Generate src/gen_vp.jai from llvm/include/llvm/IR/VPIntrinsics.def.

The .def file is run through the C preprocessor with the property macros defined to emit markers; every VP
intrinsic becomes one Vp_Info row: mask / EVL operand positions (-1 = none), the functional IR opcode, the
functional intrinsic, the constrained-FP intrinsic, and the BINARYOP / NO_FUNCTIONAL properties (the data behind
VPIntrinsic::getMaskParamPos, getVectorLengthParamPos, getFunctionalOpcodeForVP, getFunctionalIntrinsicIDForVP,
getConstrainedIntrinsicIDForVP, VPBinOpIntrinsic::isVPBinOp in llvm/lib/IR/IntrinsicInst.cpp).
"""
import subprocess
from pathlib import Path

LLVM_INC = "/opt/llvm-project-23.1.5/llvm/include"
OUT = Path(__file__).resolve().parent.parent / "src" / "gen_vp.jai"

SRC = r'''
#define BEGIN_REGISTER_VP_INTRINSIC(VPID, MASKPOS, EVLPOS) @BEGIN VPID MASKPOS EVLPOS @
#define END_REGISTER_VP_INTRINSIC(VPID) @END VPID @
#define VP_PROPERTY_FUNCTIONAL_OPC(X_) @OPCODE X_ @
#define VP_PROPERTY_CONSTRAINEDFP(X_) @CFP X_ @
#define VP_PROPERTY_FUNCTIONAL_INTRINSIC(X_) @INTR X_ @
#define VP_PROPERTY_NO_FUNCTIONAL @NOFUNC @
#define VP_PROPERTY_BINARYOP @BINOP @
#include "llvm/IR/VPIntrinsics.def"
'''

# LLVM Instruction:: opcode names -> the Opcode enum of ir.jai
OPC = {
    "Add": "ADD", "Sub": "SUB", "Mul": "MUL", "SDiv": "SDIV", "UDiv": "UDIV", "SRem": "SREM", "URem": "UREM",
    "And": "AND", "Or": "OR", "Xor": "XOR", "Shl": "SHL", "LShr": "LSHR", "AShr": "ASHR",
    "FAdd": "FADD", "FSub": "FSUB", "FMul": "FMUL", "FDiv": "FDIV", "FRem": "FREM", "FNeg": "FNEG",
    "FCmp": "FCMP", "ICmp": "ICMP", "Load": "LOAD", "Store": "STORE", "Select": "SELECT",
    "Trunc": "TRUNC", "ZExt": "ZEXT", "SExt": "SEXT", "FPTrunc": "FPTRUNC", "FPExt": "FPEXT",
    "FPToSI": "FPTOSI", "FPToUI": "FPTOUI", "SIToFP": "SITOFP", "UIToFP": "UITOFP",
    "PtrToInt": "PTRTOINT", "IntToPtr": "INTTOPTR",
}


def intrinsic_name(i):
    # Intrinsic::masked_load -> llvm.masked.load, experimental_constrained_fadd -> llvm.experimental.constrained.fadd
    return "llvm." + i.replace("_", ".")


def main():
    out = subprocess.run(["cpp", "-P", "-I", LLVM_INC, "-"], input=SRC, capture_output=True, text=True, check=True).stdout
    toks = [t.strip() for t in out.split("@") if t.strip()]
    rows = []
    cur = None
    for t in toks:
        w = t.split()
        if w[0] == "BEGIN":
            cur = {"id": w[1], "mask": -1 if w[2] == "std::nullopt" else int(w[2]),
                   "evl": -1 if w[3] == "std::nullopt" else int(w[3]), "opc": "NONE_OP", "intr": "", "cfp": "",
                   "binop": False, "nofunc": False}
        elif w[0] == "END":
            rows.append(cur)
            cur = None
        elif cur is None:
            continue
        elif w[0] == "OPCODE":
            cur["opc"] = OPC[w[1]]
        elif w[0] == "CFP":
            cur["cfp"] = intrinsic_name(w[1])
        elif w[0] == "INTR":
            cur["intr"] = intrinsic_name(w[1])
        elif w[0] == "NOFUNC":
            cur["nofunc"] = True
        elif w[0] == "BINOP":
            cur["binop"] = True
    lines = [
        "// Generated by gen/gen_vp.py from llvm/include/llvm/IR/VPIntrinsics.def. Do not edit.",
        "",
        "Vp_Info :: struct { name: string; mask_pos: s8; evl_pos: s8; opcode: Opcode; intr: string; cfp: string; binop: bool; no_functional: bool; }",
        "",
        "VP_INFOS :: Vp_Info.[",
    ]
    for r in rows:
        name = intrinsic_name(r["id"])
        lines.append('    .{"%s", %d, %d, .%s, "%s", "%s", %s, %s},' % (
            name, r["mask"], r["evl"], r["opc"], r["intr"], r["cfp"], "true" if r["binop"] else "false",
            "true" if r["nofunc"] else "false"))
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(rows)} VP intrinsics)")


if __name__ == "__main__":
    main()
