#!/usr/bin/env python3
"""Generates src/gen_dwarf.jai: DWARF and DI flag name tables for debug-info metadata.

From llvm/include/llvm/BinaryFormat/Dwarf.def (HANDLE_DW_TAG, _ATE, _LANG, _LNAME, _VIRTUALITY, _CC, _OP,
_APPLE_ENUM_KIND, _LLVM_LANG_DIALECT; DW_MACINFO_* and DW_OP_LLVM_* are listed in Dwarf.h / Dwarf.cpp) and
llvm/include/llvm/IR/DebugInfoFlags.def (HANDLE_DI_FLAG, HANDLE_DISP_FLAG, in definition order: DINode::splitFlags
emits flags in that order). Run: python3 impl/jai/gen/gen_dwarf.py > impl/jai/src/gen_dwarf.jai
"""
import re
L = '/opt/llvm-project-23.1.5/llvm/include/llvm/'
dw = open(L + 'BinaryFormat/Dwarf.def').read()
# drop the macro default definitions at the top
body = dw[dw.index('HANDLE_DW_TAG(0x0000'):] if 'HANDLE_DW_TAG(0x0000' in dw else dw

def ev(x):
    x = x.strip()
    x = x.replace('u', '') if re.fullmatch(r'[0-9a-fA-Fx()<| u]+', x) else x
    return eval(x)

def collect(macro, prefix, name_idx=1):
    out = []
    for m in re.finditer(r'^' + macro + r'\(([^)]*(?:\([^)]*\)[^)]*)*)\)', body, re.M):
        args = [a.strip() for a in m.group(1).split(',')]
        out.append((ev(args[0]), prefix + args[name_idx]))
    return out

tables = {
    'DW_TAG': collect('HANDLE_DW_TAG', 'DW_TAG_'),
    'DW_ATE': collect('HANDLE_DW_ATE', 'DW_ATE_'),
    'DW_LANG': collect('HANDLE_DW_LANG', 'DW_LANG_'),
    'DW_LNAME': collect('HANDLE_DW_LNAME', 'DW_LNAME_'),
    'DW_VIRTUALITY': collect('HANDLE_DW_VIRTUALITY', 'DW_VIRTUALITY_'),
    'DW_CC': collect('HANDLE_DW_CC', 'DW_CC_'),
    'DW_OP': collect('HANDLE_DW_OP', 'DW_OP_') + [
        (0x1000, 'DW_OP_LLVM_fragment'), (0x1001, 'DW_OP_LLVM_convert'), (0x1002, 'DW_OP_LLVM_tag_offset'),
        (0x1003, 'DW_OP_LLVM_entry_value'), (0x1004, 'DW_OP_LLVM_implicit_pointer'), (0x1005, 'DW_OP_LLVM_arg'),
        (0x1006, 'DW_OP_LLVM_extract_bits_sext'), (0x1007, 'DW_OP_LLVM_extract_bits_zext')],
    'DW_MACINFO': [(1, 'DW_MACINFO_define'), (2, 'DW_MACINFO_undef'), (3, 'DW_MACINFO_start_file'),
                   (4, 'DW_MACINFO_end_file'), (0xff, 'DW_MACINFO_vendor_ext')],
    'DW_APPLE_ENUM_KIND': collect('HANDLE_DW_APPLE_ENUM_KIND', 'DW_APPLE_ENUM_KIND_'),
    'DW_LLVM_LANG_DIALECT': collect('HANDLE_DW_LLVM_LANG_DIALECT', 'DW_LLVM_LANG_DIALECT_'),
}
fl = open(L + 'IR/DebugInfoFlags.def').read()
fl = fl[:fl.index('#ifdef DI_FLAG_LARGEST_NEEDED')] + fl[fl.index('#endif', fl.index('#ifdef DI_FLAG_LARGEST_NEEDED')):]
fl = fl[:fl.index('#ifdef DISP_FLAG_LARGEST_NEEDED')] + fl[fl.index('#endif', fl.index('#ifdef DISP_FLAG_LARGEST_NEEDED')):]
def flags(macro, prefix):
    out = []
    for m in re.finditer(r'^' + macro + r'\((.*), (\w+)\)', fl, re.M):
        out.append((eval(m.group(1).replace('1u', '1').replace('2u', '2')), prefix + m.group(2)))
    return out
tables['DI_FLAG'] = flags('HANDLE_DI_FLAG', 'DIFlag')
tables['DISP_FLAG'] = flags('HANDLE_DISP_FLAG', 'DISPFlag')

print('// GENERATED by impl/jai/gen/gen_dwarf.py from Dwarf.def and DebugInfoFlags.def. Do not edit.')
print('Dwarf_Name :: struct { value: u64; name: string; }')
for k, rows in tables.items():
    print('%s_NAMES :: Dwarf_Name.[' % k)
    for v, n in rows:
        print('    .{%d, "%s"},' % (v, n))
    print('];')
