#!/usr/bin/env python3
"""Generates src/gen_vecfuncs.jai from llvm/include/llvm/Analysis/VecFuncs.def: one `Vec_Desc` table per
`TLI_DEFINE_*_VECFUNCS` section, in file order, like the VecFuncs_* arrays of lib/Analysis/TargetLibraryInfo.cpp.

TLI_DEFINE_VECFUNC takes 4 (SCAL, VEC, VF, VABI_PREFIX), 5 (+ MASK before VABI_PREFIX) or 6 (+ CC) arguments
depending on the section; missing MASK is NOMASK and missing CC is NOCC (std::nullopt, cc = -1 here).
CallingConv::AArch64_VectorCall is 97 (include/llvm/IR/CallingConv.h).

Usage: python3 impl/jai/gen/gen_vecfuncs.py > impl/jai/src/gen_vecfuncs.jai
"""
import re

SRC = '/opt/llvm-project-23.1.5/llvm/include/llvm/Analysis/VecFuncs.def'
CC = {'CallingConv::AArch64_VectorCall': 97, 'NOCC': -1}
SECTIONS = {
    'TLI_DEFINE_ACCELERATE_VECFUNCS': 'VECFUNCS_ACCELERATE',
    'TLI_DEFINE_DARWIN_LIBSYSTEM_M_VECFUNCS': 'VECFUNCS_DARWIN_LIBSYSTEM_M',
    'TLI_DEFINE_LIBMVEC_X86_VECFUNCS': 'VECFUNCS_LIBMVEC_X86',
    'TLI_DEFINE_LIBMVEC_AARCH64_VECFUNCS': 'VECFUNCS_LIBMVEC_AARCH64',
    'TLI_DEFINE_MASSV_VECFUNCS': 'VECFUNCS_MASSV',
    'TLI_DEFINE_SVML_VECFUNCS': 'VECFUNCS_SVML',
    'TLI_DEFINE_SLEEFGNUABI_VF2_VECFUNCS': 'VECFUNCS_SLEEFGNUABI_VF2',
    'TLI_DEFINE_SLEEFGNUABI_VF4_VECFUNCS': 'VECFUNCS_SLEEFGNUABI_VF4',
    'TLI_DEFINE_SLEEFGNUABI_SCALABLE_VECFUNCS': 'VECFUNCS_SLEEFGNUABI_VFSCALABLE',
    'TLI_DEFINE_SLEEFGNUABI_SCALABLE_VECFUNCS_RISCV': 'VECFUNCS_SLEEFGNUABI_VFSCALABLE_RISCV',
    'TLI_DEFINE_ARMPL_VECFUNCS': 'VECFUNCS_ARMPL',
    'TLI_DEFINE_AMDLIBM_VECFUNCS': 'VECFUNCS_AMDLIBM',
}

text = re.sub(r'//[^\n]*', '', open(SRC).read())
tables = {}
cur = None
for line in text.split('\n'):
    s = line.strip()
    m = re.match(r'#(?:el)?if defined\((\w+)\)', s)
    if m:
        cur = SECTIONS[m.group(1)]
        tables[cur] = []
        continue
    if s.startswith('#else') or s.startswith('#endif'):
        cur = None
        continue
    if cur is None or not s.startswith('TLI_DEFINE_VECFUNC('):
        continue
    args = [a.strip() for a in re.match(r'TLI_DEFINE_VECFUNC\((.*)\)\s*$', s).group(1).split(',')]
    if len(args) == 4:
        scal, vec, vf, prefix = args; mask = 'NOMASK'; cc = 'NOCC'
    elif len(args) == 5:
        scal, vec, vf, mask, prefix = args; cc = 'NOCC'
    elif len(args) == 6:
        scal, vec, vf, mask, prefix, cc = args
    else:
        raise SystemExit('bad entry: ' + s)
    vm = re.match(r'(FIXED|SCALABLE)\((\d+)\)', vf)
    assert vm and mask in ('NOMASK', 'MASKED'), s
    tables[cur].append((scal, vec, int(vm.group(2)), vm.group(1) == 'SCALABLE', mask == 'MASKED', prefix, CC[cc]))

assert set(tables) == set(SECTIONS.values()), set(SECTIONS.values()) - set(tables)
print('// Generated by impl/jai/gen/gen_vecfuncs.py from llvm/include/llvm/Analysis/VecFuncs.def. Do not edit.')
print('// Vec_Desc rows: scalar name, vector name, VF, scalable, masked, VABI prefix, calling convention (-1: none).')
print()
print('Vec_Desc :: struct { scalar: string; vector: string; vf: u32; scalable: bool; masked: bool; vabi_prefix: string; cc: s32; }')
for name in SECTIONS.values():
    print()
    print('%s :: Vec_Desc.[' % name)
    for scal, vec, vf, sc, mk, prefix, cc in tables[name]:
        print('    .{%s, %s, %d, %s, %s, %s, %d},' % (scal, vec, vf, 'true' if sc else 'false', 'true' if mk else 'false', prefix, cc))
    print('];')
