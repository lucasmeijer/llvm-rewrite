#!/usr/bin/env python3
"""Generates src/gen_passes.goose: every pass and analysis name LLVM's PassBuilder knows
(llvm/lib/Passes/PassRegistry.def), tagged with its level. Used by the pipeline parser to tell an unknown
pass (error, like PassBuilder) from a known LLVM pass we haven't ported (error: not implemented yet), and to
decide how a pipeline whose outer level is implicit gets wrapped (PassBuilder::parsePassPipeline).

Entry format: "<tag>:<name>", tag = m/c/f/l/n (module, cgscc, function, loop, loop-nest) for passes,
mp/cp/fp/lp (the same, with parameters `name<...>`), ma/ca/fa/la (analyses: require<>/invalidate<>).
"""
import re, sys
DEF = "/opt/llvm-project-23.1.5/llvm/lib/Passes/PassRegistry.def"
src = open(DEF).read()
src = re.sub(r"//[^\n]*", "", src)
tags = {
    "MODULE_PASS": "m", "MODULE_PASS_WITH_PARAMS": "mp", "MODULE_ANALYSIS": "ma", "MODULE_ALIAS_ANALYSIS": "ma",
    "CGSCC_PASS": "c", "CGSCC_PASS_WITH_PARAMS": "cp", "CGSCC_ANALYSIS": "ca",
    "FUNCTION_PASS": "f", "FUNCTION_PASS_WITH_PARAMS": "fp", "FUNCTION_ANALYSIS": "fa",
    "FUNCTION_ALIAS_ANALYSIS": "fa",
    "LOOP_PASS": "l", "LOOP_PASS_WITH_PARAMS": "lp", "LOOP_ANALYSIS": "la", "LOOPNEST_PASS": "n",
}
entries = []
seen = set()
for m in re.finditer(r"^([A-Z_]+)\(\s*\"([^\"]+)\"", src, re.M):
    macro, name = m.groups()
    if macro not in tags:
        continue
    e = tags[macro] + ":" + name
    if e in seen:
        continue
    seen.add(e)
    entries.append(e)
out = ["// Generated by tools/gen_passes.py from llvm/lib/Passes/PassRegistry.def. Do not edit.",
       "// \"<tag>:<name>\"; tag m/c/f/l/n = module/cgscc/function/loop/loop-nest pass, +p = with parameters,",
       "// ma/ca/fa/la = analysis (require<name>, invalidate<name>).",
       "let LLVM_PASS_NAMES: const u8[:][] = ["]
for e in entries:
    out.append(f'    "{e}",')
out.append("];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_passes.goose", "w").write("\n".join(out) + "\n")
print(len(entries), "pass names")
