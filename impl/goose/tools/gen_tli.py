#!/usr/bin/env python3
"""Generates src/gen_tli.goose from llvm/include/llvm/Analysis/TargetLibraryInfo.td: the library functions
TargetLibraryInfo knows (LibFunc enum = def order), their names, and their prototype signatures, plus the
allocation/free tables of llvm/lib/Analysis/MemoryBuiltins.cpp (AllocationFnData, FreeFnData).

Signature string: one letter per type id, return type first:
  v Void, b Bool, h Int16, w Int32, i Int, I IntPlus, l Long, x IntX, q Int64, L LLong, z SizeT, Z SSizeT,
  f Flt, d Dbl, D LDbl, F Floating, p Ptr, s Struct, e Ellip, = Same.
"""
import re, sys
TD = "/opt/llvm-project-23.1.5/llvm/include/llvm/Analysis/TargetLibraryInfo.td"
MB = "/opt/llvm-project-23.1.5/llvm/lib/Analysis/MemoryBuiltins.cpp"
code = {"Void": "v", "Bool": "b", "Int16": "h", "Int32": "w", "Int": "i", "IntPlus": "I", "Long": "l",
        "IntX": "x", "Int64": "q", "LLong": "L", "SizeT": "z", "SSizeT": "Z", "Flt": "f", "Dbl": "d",
        "LDbl": "D", "Floating": "F", "Ptr": "p", "Struct": "s", "Ellip": "e", "Same": "=", "?": "?"}
src = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", open(TD).read()), flags=re.S)
defs = []
for m in re.finditer(r"\bdef\s+(\w+)\s*:\s*TargetLibCall<\s*\"([^\"]*)\"\s*,\s*(\w+|\?)\s*(?:,\s*\[([^\]]*)\])?\s*>", src, re.S):
    d, s, ret, args = m.groups()
    sig = "?" if ret == "?" else code[ret] + "".join(code[a.strip()] for a in (args or "").split(",") if a.strip())
    defs.append((d, s, sig))
mb = open(MB).read()
alloc = re.findall(r"\{LibFunc_(\w+),\s*\{(\w+),\s*(\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),", mb)
free = re.findall(r"\{LibFunc_(\w+),\s*\{(\d+),\s*MallocFamily", mb)
idx = {d: i for i, (d, _, _) in enumerate(defs)}
out = ["// Generated by tools/gen_tli.py from TargetLibraryInfo.td and MemoryBuiltins.cpp. Do not edit.",
       "// LibFunc ids are 0-based in TargetLibraryInfo.td def order (LLVM's enum order).", ""]
for i, (d, s, sig) in enumerate(defs):
    out.append(f"let LF_{d} = {i};")
out.append(f"let LF_COUNT = {len(defs)};")
out.append("let TLI_NAMES: const u8[:][] = [" + ", ".join('"' + s.replace("\\", "\\\\") + '"' for _, s, _ in defs) + "];")
out.append("let TLI_DEFS: const u8[:][] = [" + ", ".join(f'"{d}"' for d, _, _ in defs) + "];")
out.append("let TLI_SIGS: const u8[:][] = [" + ", ".join(f'"{sig}"' for _, _, sig in defs) + "];")
order = sorted(range(len(defs)), key=lambda i: defs[i][1].encode())
out.append("let TLI_SORTED: i32[] = [" + ", ".join(str(i) for i in order) + "];")
# alloc: lf, alloctype (1 OpNewLike, 2 MallocLike, 4 StrDupLike), nparams, fst, snd
ty = {"OpNewLike": 1, "MallocLike": 2, "StrDupLike": 4}
out.append("// (LibFunc, AllocType bits: 1 OpNewLike 2 MallocLike 4 StrDupLike, NumParams, FstParam, SndParam, AlignParam)")
out.append("let TLI_ALLOC_DATA: i32[] = [" + ", ".join(f"{idx[a[0]]}, {ty[a[1]]}, {a[2]}, {a[3]}, {a[4]}, {a[5]}" for a in alloc) + "];")
out.append("// (LibFunc, NumParams)")
out.append("let TLI_FREE_DATA: i32[] = [" + ", ".join(f"{idx[f[0]]}, {f[1]}" for f in free) + "];")
# MallocFamily of each AllocationFnData / FreeFnData entry (same order as the tables above); names are
# mangledNameForMallocFamily
fams = re.findall(r"^\s*(\w+),", re.search(r"enum class MallocFamily \{(.*?)\};", mb, re.S).group(1), re.M)
famname = dict(re.findall(r"case MallocFamily::(\w+):\s*return \"([^\"]*)\";", mb))
afam = re.findall(r"\{LibFunc_\w+,\s*\{\w+,\s*\d+,\s*-?\d+,\s*-?\d+,\s*-?\d+,\s*MallocFamily::(\w+)\}", mb)
ffam = re.findall(r"\{LibFunc_\w+,\s*\{\d+,\s*MallocFamily::(\w+)\}", mb)
assert len(afam) == len(alloc) and len(ffam) == len(free)
out.append("// MallocFamily names (mangledNameForMallocFamily), in enum order")
out.append("let TLI_FAMILY_NAMES: const u8[:][] = [" + ", ".join('"' + famname[f] + '"' for f in fams) + "];")
out.append("// MallocFamily index of each TLI_ALLOC_DATA entry and of each TLI_FREE_DATA entry")
out.append("let TLI_ALLOC_FAMILY: i32[] = [" + ", ".join(str(fams.index(f)) for f in afam) + "];")
out.append("let TLI_FREE_FAMILY: i32[] = [" + ", ".join(str(fams.index(f)) for f in ffam) + "];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_tli.goose", "w").write("\n".join(out) + "\n")
print(len(defs), "lib funcs,", len(alloc), "alloc,", len(free), "free")
