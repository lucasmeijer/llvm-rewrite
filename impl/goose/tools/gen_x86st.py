#!/usr/bin/env python3
"""Generates src/gen_x86st.goose: the X86 subtarget's CPU and feature names (the SubtargetSubTypeKV and
SubtargetFeatureKV tables of X86GenSubtargetInfo.inc), read from `llc -mtriple=x86_64 -mattr=help`."""
import os, subprocess
out = subprocess.run(["/opt/llvm-23.1.5/bin/llc", "-mtriple=x86_64", "-mattr=help"], capture_output=True, text=True)
text = out.stdout + out.stderr
cpus, feats, cur = [], [], None
for line in text.splitlines():
    if line.startswith("Available CPUs"): cur = cpus; continue
    if line.startswith("Available features"): cur = feats; continue
    if line.startswith("Use +feature"): cur = None; continue
    if cur is not None and line.startswith("  ") and " - " in line:
        cur.append(line.split()[0])
assert len(cpus) > 100 and len(feats) > 150
blob = lambda xs: "\\n" + "\\n".join(xs) + "\\n"
src = ["// Generated by tools/gen_x86st.py (LLVM 23.1.5, `llc -mattr=help`). Do not edit.",
       "// Newline-delimited (leading and trailing newline) X86 processor and feature names.",
       'let X86_CPU_NAMES: const u8[:] = "%s";' % blob(cpus),
       'let X86_FEATURE_NAMES: const u8[:] = "%s";' % blob(feats)]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../src/gen_x86st.goose"), "w").write("\n".join(src) + "\n")
print(len(cpus), len(feats))
