#!/usr/bin/env python3
"""Generates src/gen_dwarf.goose: DWARF and DIFlag name tables used by the !DI* metadata parser and printer.
Source: llvm/include/llvm/BinaryFormat/Dwarf.def, Dwarf.h (LLVM-only ops) and llvm/include/llvm/IR/DebugInfoFlags.def.
Each table is two parallel arrays NAME_<T> / VAL_<T> in .def order (the order the printers iterate)."""
import os, re
L = "/opt/llvm-project-23.1.5/llvm/include/llvm/"
d = open(L + "BinaryFormat/Dwarf.def").read()
def grab(macro, prefix, nargs_name=1):
    out = []
    for m in re.finditer(r"^" + macro + r"\(([^,]+),\s*([A-Za-z0-9_]+)", d, re.M):
        out.append((prefix + m.group(2), int(m.group(1), 0)))
    return out
tables = {
    "TAG": grab("HANDLE_DW_TAG", "DW_TAG_"),
    "ATE": grab("HANDLE_DW_ATE", "DW_ATE_"),
    "LANG": grab("HANDLE_DW_LANG", "DW_LANG_"),
    "LNAME": grab("HANDLE_DW_LNAME", "DW_LNAME_"),
    "CC": grab("HANDLE_DW_CC", "DW_CC_"),
    "VIRT": grab("HANDLE_DW_VIRTUALITY", "DW_VIRTUALITY_"),
    "ENUMKIND": grab("HANDLE_DW_APPLE_ENUM_KIND", "DW_APPLE_ENUM_KIND_"),
    "DIALECT": grab("HANDLE_DW_LLVM_LANG_DIALECT", "DW_LLVM_LANG_DIALECT_"),
    "OP": grab("HANDLE_DW_OP", "DW_OP_") + [("DW_OP_LLVM_convert", 0x1001), ("DW_OP_LLVM_fragment", 0x1000),
        ("DW_OP_LLVM_tag_offset", 0x1002), ("DW_OP_LLVM_entry_value", 0x1003), ("DW_OP_LLVM_implicit_pointer", 0x1004),
        ("DW_OP_LLVM_arg", 0x1005), ("DW_OP_LLVM_extract_bits_sext", 0x1006), ("DW_OP_LLVM_extract_bits_zext", 0x1007)],
    "MACINFO": [("DW_MACINFO_define", 1), ("DW_MACINFO_undef", 2), ("DW_MACINFO_start_file", 3),
        ("DW_MACINFO_end_file", 4), ("DW_MACINFO_vendor_ext", 0xff)],
}
f = open(L + "IR/DebugInfoFlags.def").read()
f = re.sub(r"#ifdef DI_FLAG_LARGEST_NEEDED.*?#endif", "", f, flags=re.S)
def ev(e): return eval(e.replace("u", ""))
tables["DIFLAG"] = [("DIFlag" + n, ev(v)) for v, n in re.findall(r"^HANDLE_DI_FLAG\((.+), (\w+)\)", f, re.M)]
tables["SPFLAG"] = [("DISPFlag" + n, ev(v)) for v, n in re.findall(r"^HANDLE_DISP_FLAG\((.+), (\w+)\)", f, re.M)]
out = ["// Generated by tools/gen_dwarf.py from Dwarf.def and DebugInfoFlags.def (LLVM 23.1.5). Do not edit."]
for k, xs in tables.items():
    out.append("let NAME_%s: const u8[:][] = [%s];" % (k, ", ".join('"%s"' % n for n, _ in xs)))
    out.append("let VAL_%s: i64[] = [%s];" % (k, ", ".join(str(v) for _, v in xs)))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../src/gen_dwarf.goose"), "w").write("\n".join(out) + "\n")
print({k: len(v) for k, v in tables.items()})
