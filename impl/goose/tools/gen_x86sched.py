#!/usr/bin/env python3
"""Generate impl/goose/src/gen_x86sched.goose: the X86 processors' scheduling-model properties the middle end reads.

For every processor definition in llvm/lib/Target/X86/X86.td (`def : Proc<...>`, `def : ProcModel<...>`, including
those inside `foreach P = [...] in { ... }`), the SchedMachineModel it uses and that model's LoopMicroOpBufferSize
(MCSchedModel::LoopMicroOpBufferSize, read by BasicTTIImplBase::getUnrollingPreferences). As in TableGen's
SubtargetEmitter, a negative (unset) value becomes MCSchedModel::DefaultLoopMicroOpBufferSize = 0. `Proc<>` uses
GenericModel.

Usage: python3 impl/goose/tools/gen_x86sched.py > impl/goose/src/gen_x86sched.goose
"""
import os, re, sys

LLVM = '/opt/llvm-project-23.1.5/llvm'
X86 = os.path.join(LLVM, 'lib/Target/X86')


def strip_comments(s):
    return re.sub(r'//[^\n]*', '', s)


def model_props():
    """model name -> LoopMicroOpBufferSize (as defined, -1 when unset)"""
    props = {}
    classes = {}
    for fn in sorted(os.listdir(X86)):
        if not fn.endswith('.td'):
            continue
        s = strip_comments(open(os.path.join(X86, fn)).read())
        for m in re.finditer(r'\b(def|class)\s+(\w+)\s*:\s*(\w+)\s*\{(.*?)\n\}', s, re.S):
            kind, name, base, body = m.groups()
            v = re.search(r'\bLoopMicroOpBufferSize\s*=\s*(-?\d+)', body)
            val = int(v.group(1)) if v else None
            if kind == 'class':
                classes[name] = (base, val)
            elif base == 'SchedMachineModel' or base in classes:
                props[name] = (base, val)
        for m in re.finditer(r'\bdef\s+(\w+)\s*:\s*(\w+)\s*;', s):
            name, base = m.groups()
            if base in classes:
                props[name] = (base, None)
    out = {}
    for name, (base, val) in props.items():
        b = base
        while val is None and b in classes:
            b, val = classes[b]
        out[name] = -1 if val is None else val
    return out


def processors():
    s = strip_comments(open(os.path.join(X86, 'X86.td')).read())
    res = []
    pos = 0
    pat = re.compile(r'foreach\s+P\s*=\s*\[([^\]]*)\]\s*in\s*\{|def\s*:\s*(Proc|ProcModel)\s*<\s*("[^"]*"|P)\s*,\s*(\w+)?')
    loop_names = None
    depth_end = None
    while True:
        m = pat.search(s, pos)
        if not m:
            break
        if m.group(1) is not None:
            loop_names = re.findall(r'"([^"]*)"', m.group(1))
            # find the matching closing brace
            d = 1
            i = m.end()
            while d:
                if s[i] == '{':
                    d += 1
                elif s[i] == '}':
                    d -= 1
                i += 1
            depth_end = i
            pos = m.end()
            continue
        if depth_end is not None and m.start() >= depth_end:
            loop_names = None
            depth_end = None
        cls, nm, model = m.group(2), m.group(3), m.group(4)
        if cls == 'Proc':
            model = 'GenericModel'
        names = loop_names if nm == 'P' else [nm.strip('"')]
        for n in names:
            res.append((n, model))
        pos = m.end()
    return res


def main():
    props = model_props()
    procs = processors()
    names = []
    sizes = []
    for name, model in procs:
        if model not in props:
            sys.exit('unknown scheduling model %s for %s' % (model, name))
        v = props[model]
        names.append(name)
        sizes.append(v if v >= 0 else 0)
    out = []
    out.append('// Generated by impl/goose/tools/gen_x86sched.py from llvm/lib/Target/X86/X86.td and the X86Sched*.td models:')
    out.append('// every processor name and its scheduling model\'s LoopMicroOpBufferSize (MCSchedModel; unset = 0).')
    out.append('// Do not edit; rerun the script.')
    out.append('let X86SCHED_CPUS: const u8[:][] = [' + ', '.join('"%s"' % n for n in names) + '];')
    out.append('let X86SCHED_LOOP_UOP_BUFFER: const i32[] = [' + ', '.join(str(v) for v in sizes) + '];')
    print('\n'.join(out))


main()
