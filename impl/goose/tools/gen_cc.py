#!/usr/bin/env python3
"""Generates src/gen_cc.goose: calling convention keywords (from AsmWriter.cpp printCallingConv) and their
numbers (llvm/include/llvm/IR/CallingConv.h)."""
import os, re
L = "/opt/llvm-project-23.1.5/llvm/"
h = open(L + "include/llvm/IR/CallingConv.h").read()
vals = {m.group(1): int(m.group(2)) for m in re.finditer(r'^\s*(\w+)\s*=\s*(\d+),', h, re.M)}
a = open(L + "lib/IR/AsmWriter.cpp").read()
i = a.index("static void printCallingConv")
body = a[i:a.index("\n}\n", i)]
pairs, seen = [], set()
for m in re.finditer(r'case CallingConv::(\w+):\s*(?:\n\s*)?Out << "([\w]+ ?)";', body):
    if m.group(1) in vals and m.group(2).strip() not in seen:
        seen.add(m.group(2).strip()); pairs.append((m.group(2), vals[m.group(1)]))
out = ["// Generated by tools/gen_cc.py (LLVM 23.1.5). Do not edit. Printed names may end in a space (as LLVM's do).",
       "let CC_NAMES: const u8[:][] = [%s];" % ", ".join('"%s"' % n for n, _ in pairs),
       "let CC_VALS: i64[] = [%s];" % ", ".join(str(v) for _, v in pairs)]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../src/gen_cc.goose"), "w").write("\n".join(out) + "\n")
print(len(pairs))
