#!/usr/bin/env python3
"""Generates src/gen_triple.goose from llvm/include/llvm/TargetParser/TripleName.def, Triple.h and Triple.cpp:

- the Triple ArchType / VendorType / OSType / EnvironmentType / ObjectFormatType enums (TA_ / TV_ / TOS_ / TENV_ /
  TOF_ constants, 0 = unknown, in the enums' order),
- their canonical names (getArchTypeName, getVendorTypeName, getOSTypeName, getEnvironmentTypeName,
  getObjectFormatTypeName),
- the parse tables in source order: parseVendor (whole names, incl. aliases), parseOS / parseEnvironment (prefix
  matches in .def order, incl. aliases), and Triple::parseArch's StringSwitch (Case / Cases / StartsWith, in order;
  the ARM and BPF fallbacks are hand-written in triple.goose).

Usage: python3 tools/gen_triple.py [src/gen_triple.goose]
"""
import re, sys

L = "/opt/llvm-project-23.1.5/llvm"
DEF = re.sub(r"//[^\n]*", "", open(f"{L}/include/llvm/TargetParser/TripleName.def").read())
H = open(f"{L}/include/llvm/TargetParser/Triple.h").read()
CPP = open(f"{L}/lib/TargetParser/Triple.cpp").read()


def enum_body(name):
    body = re.search(r"enum %s \{(.*?)\};" % name, H, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    out = []
    for item in body.split(","):
        item = item.strip()
        if not item or "=" in item:
            continue
        out.append(item)
    return out


def def_table(kind):
    canon, parse = [], []
    for m in re.finditer(r"^TRIPLE_%s(_ALIAS)?\((\w+),\s*\"([^\"]*)\"\)" % kind, DEF, re.M):
        alias, enum, name = m.groups()
        if not alias:
            canon.append((enum, name))
        parse.append((enum, name))
    return canon, parse


def strlist(xs):
    return "[" + ", ".join('"%s"' % x for x in xs) + "]"


out = ["// Generated by tools/gen_triple.py from llvm/include/llvm/TargetParser/TripleName.def, Triple.h and",
       "// lib/TargetParser/Triple.cpp. Do not edit.", ""]

# ArchType: enum order from Triple.h, names from getArchTypeName
arch_enum = enum_body("ArchType")
assert arch_enum[0] == "UnknownArch"
for i, a in enumerate(arch_enum):
    out.append(f"let TA_{a}: i32 = {i};")
names_src = re.search(r"StringRef Triple::getArchTypeName\(ArchType Kind\) \{(.*?)\n\}", CPP, re.S).group(1)
arch_name = {}
cur = []
for line in names_src.split("\n"):
    m = re.match(r"\s*case (\w+):", line)
    if m:
        cur.append(m.group(1))
        continue
    m = re.match(r"\s*return \"([^\"]*)\";", line)
    if m:
        for c in cur:
            arch_name[c] = m.group(1)
        cur = []
out.append("let TRIPLE_ARCH_NAMES: const u8[:][] = " + strlist(arch_name[a] for a in arch_enum) + ";")

# parseArch StringSwitch
pa = re.search(r"Triple::ArchType Triple::parseArch\(StringRef ArchName\) \{(.*?)\.Default\(Triple::UnknownArch\);", CPP, re.S).group(1)
pa = re.sub(r"//[^\n]*", "", pa)
pnames, pkinds, pids = [], [], []
for m in re.finditer(r"\.(Case|Cases|StartsWith)\(\s*(\{[^}]*\}|\"[^\"]*\")\s*,\s*Triple::(\w+)\s*\)", pa, re.S):
    kind, strs, arch = m.groups()
    for s in re.findall(r"\"([^\"]*)\"", strs):
        pnames.append(s)
        pkinds.append(1 if kind == "StartsWith" else 0)
        pids.append(arch_enum.index(arch))
out.append("// Triple::parseArch's StringSwitch in order: name, 1 = StartsWith (else exact), ArchType")
out.append("let TRIPLE_ARCH_PARSE_NAMES: const u8[:][] = " + strlist(pnames) + ";")
out.append("let TRIPLE_ARCH_PARSE_PREFIX: i32[] = [" + ", ".join(map(str, pkinds)) + "];")
out.append("let TRIPLE_ARCH_PARSE_IDS: i32[] = [" + ", ".join(map(str, pids)) + "];")

for kind, pre, unk, ename in (("VENDOR", "TV_", "UnknownVendor", "VendorType"), ("OS", "TOS_", "UnknownOS", "OSType"),
                              ("ENV", "TENV_", "UnknownEnvironment", "EnvironmentType")):
    canon, parse = def_table(kind)
    enum = enum_body(ename)
    assert enum[0] == unk, (enum[0], unk)
    cname = dict(canon)
    assert sorted(cname) == sorted(enum[1:]), kind
    for i, e in enumerate(enum):
        out.append(f"let {pre}{e}: i32 = {i};")
    out.append(f"let TRIPLE_{kind}_NAMES: const u8[:][] = " + strlist(["unknown"] + [cname[e] for e in enum[1:]]) + ";")
    out.append(f"let TRIPLE_{kind}_PARSE_NAMES: const u8[:][] = " + strlist(n for _, n in parse) + ";")
    out.append(f"let TRIPLE_{kind}_PARSE_IDS: i32[] = [" + ", ".join(str(enum.index(e)) for e, _ in parse) + "];")

fmt = enum_body("ObjectFormatType")
for i, f in enumerate(fmt):
    out.append(f"let TOF_{f}: i32 = {i};")
fsrc = re.search(r"StringRef Triple::getObjectFormatTypeName\(ObjectFormatType Kind\) \{(.*?)\n\}", CPP, re.S).group(1)
fname = dict(re.findall(r"case (\w+):\s*return \"([^\"]*)\";", fsrc))
out.append("let TRIPLE_OF_NAMES: const u8[:][] = " + strlist(fname[f] for f in fmt) + ";")

open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_triple.goose", "w").write("\n".join(out) + "\n")
print(len(arch_enum), "archs,", len(pnames), "arch parse names")
