#!/usr/bin/env python3
"""Generates src/gen_iids.goose: intrinsic IDs (llvm/include/llvm/IR/Intrinsics.td and IntrinsicsX86.td).

LLVM names an intrinsic `def int_foo_bar` "llvm.foo.bar" unless the record gives an explicit "llvm.…" name.
IDs here are our own numbering (index in the sorted name table, 1-based; 0 = not an intrinsic), not LLVM's
enum values; passes compare against the generated `IID_<def name>` constants. The table is sorted so that
`intrinsic_lookup` (instinfo.goose) can do LLVM's longest-prefix match (Intrinsic::lookupIntrinsicID).
Overloaded intrinsics (any `llvm_any*` / `llvm_anyptr` type in the signature) are flagged: only those may
carry a ".<type suffix>" after the base name.
"""
import re, sys
TDS = ["/opt/llvm-project-23.1.5/llvm/include/llvm/IR/Intrinsics.td",
       "/opt/llvm-project-23.1.5/llvm/include/llvm/IR/IntrinsicsX86.td"]
recs = {}
for td in TDS:
    src = open(td).read()
    src = re.sub(r"//[^\n]*", "", src)
    for m in re.finditer(r"\bdef\s+int_(\w+)(#n)?\s*:", src):
        base, hashn = m.groups()
        end = src.find(";", m.end())
        body = src[m.end():end]
        ov = bool(re.search(r"llvm_any\w*_ty|llvm_anyptr_ty", body))
        ex = re.search(r'"(llvm\.[^"]+)"', body)
        names = []
        if hashn:
            for n in range(2, 9):
                names.append((base + str(n), "llvm." + (base + str(n)).replace("_", ".")))
        elif ex:
            names.append((base, ex.group(1)))
        else:
            names.append((base, "llvm." + base.replace("_", ".")))
        for d, nm in names:
            recs[nm] = (d, ov)
names = sorted(recs)
out = ["// Generated by tools/gen_iids.py from Intrinsics.td and IntrinsicsX86.td. Do not edit.",
       "// Intrinsic ids: 1-based index into INTRINSIC_NAMES (sorted); 0 = not an intrinsic / unknown.", ""]
for i, nm in enumerate(names):
    out.append(f"let IID_{recs[nm][0]} = {i + 1};")
out.append("let INTRINSIC_NAMES: const u8[:][] = [\"\",")
for nm in names:
    out.append(f'    "{nm}",')
out.append("];")
out.append("let INTRINSIC_OVERLOADED: bool[] = [false, " + ", ".join("true" if recs[n][1] else "false" for n in names) + "];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_iids.goose", "w").write("\n".join(out) + "\n")
print(len(names), "intrinsics")
