#!/usr/bin/env python3
"""Generates src/gen_iids.goose: a named constant per intrinsic, `IID_<llvm name minus "llvm.", dots -> _>`,
equal to LLVM's Intrinsic::ID (the index in INTR_NAMES of src/gen_intrinsics.goose, which is generated from
LLVM's TableGen output by tools/gen_intrinsics.py). Use with func_iid() from src/intrinsics.goose.
Rerun after regenerating gen_intrinsics.goose.
"""
import re, sys
src = open("src/gen_intrinsics.goose").read()
m = re.search(r'let INTR_NAMES_BLOB: const u8\[:\] = "(.*?)";', src, re.S)
names = m.group(1).split("\\n")
out = ["// Generated by tools/gen_iids.py from src/gen_intrinsics.goose. Do not edit.",
       "// IID_x = LLVM's Intrinsic::ID of llvm.x (dots become underscores); compare with func_iid().", ""]
seen = set()
for i, n in enumerate(names):
    if i == 0:
        continue
    c = "IID_" + n[5:].replace(".", "_")
    if c in seen:
        continue
    seen.add(c)
    out.append(f"let {c} = {i};")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_iids.goose", "w").write("\n".join(out) + "\n")
print(len(seen), "intrinsic ids")
