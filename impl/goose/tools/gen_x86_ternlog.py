#!/usr/bin/env python3
"""Generates src/gen_x86_ternlog.goose from llvm/lib/Target/X86/X86InstCombineIntrinsic.cpp: the switch of
simplifyTernarylogic (one entry per immediate, its statements in source order).

Each immediate's program is a ';'-separated list of statements "<cond>:<expr>", where <cond> is the constness
requirement ("" = none, else letters of A/B/C that must be immediate constants) and <expr> is the right-hand side in
the source's prefix form (Or/Xor/And/Not/Nor/Xnor/Nand over A, B, C), "0" for the null value or "1" for all-ones.

Usage: python3 tools/gen_x86_ternlog.py [src/gen_x86_ternlog.goose]
"""
import re, sys

SRC = "/opt/llvm-project-23.1.5/llvm/lib/Target/X86/X86InstCombineIntrinsic.cpp"
s = open(SRC).read()
body = s[s.index("static Value *simplifyTernarylogic("):]
body = body[body.index("switch (Imm) {"):body.index('assert((Res.first == nullptr || Res.second == Imm)')]
progs = {}
for m in re.finditer(r"case (0x[0-9a-fA-F]+):(.*?)break;", body, re.S):
    imm = int(m.group(1), 16)
    stmts = []
    for line in m.group(2).strip().split("\n"):
        line = line.strip()
        if not line:
            continue
        stmts.append(line)
    out = []
    i = 0
    while i < len(stmts):
        st = stmts[i]
        cond = ""
        cm = re.match(r"if \((\w+)IsConst\)$", st)
        if cm:
            cond = cm.group(1)
            i += 1
            st = stmts[i]
        rm = re.match(r"Res = (.*);$", st)
        assert rm, (imm, st)
        e = rm.group(1).replace(" ", "")
        e = re.sub(r"std::move\((\w)\)", r"\1", e)
        if e == "{Constant::getNullValue(Ty),0}":
            e = "0"
        elif e == "{Constant::getAllOnesValue(Ty),0xff}":
            e = "1"
        assert re.fullmatch(r"[A-Za-z(),01]+", e), e
        out.append(cond + ":" + e)
        i += 1
    progs[imm] = ";".join(out)
assert len(progs) == 256, len(progs)
lines = ["// Generated by tools/gen_x86_ternlog.py from llvm/lib/Target/X86/X86InstCombineIntrinsic.cpp",
         "// (simplifyTernarylogic's switch). Do not edit.", "",
         "let X86_TERNLOG: const u8[:][] = ["]
for k in range(256):
    lines.append('    "%s",' % progs[k])
lines.append("];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_x86_ternlog.goose", "w").write("\n".join(lines) + "\n")
print(256, "immediates")
