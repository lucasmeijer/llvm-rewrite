#!/usr/bin/env python3
"""Generates src/gen_libfunc_attrs.goose from llvm/lib/Transforms/Utils/BuildLibCalls.cpp: the switch of
inferNonMandatoryLibFuncAttrs as a little program (one statement per line of the switch, LLVM's order) and the
entry statement of every LibFunc case label. blc_infer (build_libcalls.goose) interprets it, so fallthroughs,
breaks and the early `return Changed` behave as in the C++.

Statement text: `<setter>` or `<setter> <args...>` (setter = the static helper's name without "set"),
`AllocFamily <name>` or `AllocFamily ?<LibFunc>:<then>:<else>` (the ternaries), `AllocKind <bits>`,
`AllocSize <a> <b or -1>`, `break`, `return`. Lines are separated by '|'.
"""
import re, sys
BLC = "/opt/llvm-project-23.1.5/llvm/lib/Transforms/Utils/BuildLibCalls.cpp"
TD = "/opt/llvm-project-23.1.5/llvm/include/llvm/Analysis/TargetLibraryInfo.td"
src = open(BLC).read()
body = src[src.index("  switch (TheLibFunc) {", src.index("bool llvm::inferNonMandatoryLibFuncAttrs(Function &F")):]
body = body[:body.index("\n  default:\n    // FIXME")]
body = re.sub(r"//[^\n]*", "", body)
# join continuation lines of statements
stmts = []
entries = {}
kinds = {"Alloc": 1, "Realloc": 2, "Free": 4, "Uninitialized": 8, "Zeroed": 16, "Aligned": 32}
buf = ""
for line in body.split("\n")[1:]:
    t = line.strip()
    if not t: continue
    buf = (buf + " " + t).strip() if buf else t
    if not (buf.endswith(";") or buf.endswith(":")): continue
    s, buf = re.sub(r"\( ", "(", buf), ""
    m = re.match(r"case LibFunc_(\w+):$", s)
    if m: entries[m.group(1)] = len(stmts); continue
    if s == "break;": stmts.append("break"); continue
    if s == "[[fallthrough]];": continue
    if s == "return Changed;": stmts.append("return"); continue
    m = re.match(r"Changed \|= set(\w+)\(F(?:, (.*))?\);$", s)
    if not m: sys.exit("cannot parse: " + s)
    name, args = m.group(1), m.group(2)
    if name == "AllocFamily":
        m2 = re.match(r'TheLibFunc == LibFunc_(\w+) \? "(\w+)"\s*: "(\w+)"$', args)
        stmts.append(f"AllocFamily ?{m2.group(1)}:{m2.group(2)}:{m2.group(3)}" if m2 else "AllocFamily " + args.strip('"'))
    elif name == "AllocKind":
        stmts.append("AllocKind " + str(sum(kinds[k.strip()[len("AllocFnKind::"):]] for k in args.split("|"))))
    elif name == "AllocSize":
        a, b = [x.strip() for x in args.split(",")]
        stmts.append(f"AllocSize {a} {-1 if b == 'std::nullopt' else b}")
    else:
        stmts.append(name + ("" if args is None else " " + args))
# LibFunc ids (TargetLibraryInfo.td def order, as gen_tli.py)
tdsrc = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", open(TD).read()), flags=re.S)
defs = [m.group(1) for m in re.finditer(r"\bdef\s+(\w+)\s*:\s*TargetLibCall<", tdsrc)]
idx = {d: i for i, d in enumerate(defs)}
for s in stmts:
    if s.startswith("AllocFamily ?"): assert s.split("?")[1].split(":")[0] in idx
ent = [-1] * len(defs)
for k, v in entries.items(): ent[idx[k]] = v
out = ["// Generated by tools/gen_libfunc_attrs.py from BuildLibCalls.cpp (inferNonMandatoryLibFuncAttrs). Do not edit.",
       f"let BLC_PROG: const u8[:] = \"{'|'.join(stmts)}\";",
       "// entry statement of each LibFunc (TargetLibraryInfo.td order), -1 = default:",
       f"let BLC_ENTRY: const u8[:] = \"{','.join(str(e) for e in ent)}\";"]
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_libfunc_attrs.goose", "w").write("\n".join(out) + "\n")
print(len(stmts), "statements,", len(entries), "case labels")
