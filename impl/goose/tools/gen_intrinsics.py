#!/usr/bin/env python3
"""Generates src/gen_intrinsics.goose: the attributes LLVM gives each intrinsic declaration.

LLVM replaces the attribute list of every intrinsic declaration with Intrinsic::getAttributes (from
Intrinsics*.td) when it parses a module (AutoUpgrade.cpp: UpgradeIntrinsicFunction). Instead of porting
TableGen, we ask the oracle: every `declare @llvm.*` in tests/ is run through `opt -S` and the resulting
return/parameter/function attributes are recorded as text, which our own attribute parser reads at startup.
Rerun after adding tests that declare new intrinsics:  python3 impl/goose/tools/gen_intrinsics.py
"""
import os, re, subprocess, sys, tempfile
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
OPT = "/opt/llvm-23.1.5/bin/opt"
decls = {}
for dp, _, fs in os.walk(os.path.join(ROOT, "tests")):
    for f in fs:
        if not f.endswith(".ll"): continue
        try: text = open(os.path.join(dp, f), errors="replace").read()
        except OSError: continue
        for m in re.finditer(r"^declare [^\n]*?@(llvm\.[\w.$-]+)\(", text, re.M):
            name = m.group(1)
            if name in decls: continue
            line = text[m.start():text.index("\n", m.start())] if "\n" in text[m.start():] else text[m.start():]
            if "%" in line.split("@")[0] or re.search(r"%[\w.]+", line): continue   # named types: skip
            line = re.sub(r"\s#\d+", "", line).rstrip()
            # A probe attribute: if it survives, LLVM did not replace the attributes (unknown intrinsic or
            # invalid signature) and the declaration keeps what the text says, so it gets no table entry.
            decls[name] = line + ' "goose-probe"'
def run(lines):
    with tempfile.NamedTemporaryFile("w", suffix=".ll", delete=False) as t:
        t.write("\n".join(lines) + "\n")
    r = subprocess.run([OPT, "-S", t.name, "-o", "-"], capture_output=True, text=True)
    os.unlink(t.name)
    return r.stdout if r.returncode == 0 else None
out = run(list(decls.values()))
if out is None:
    out = ""
    for n, l in decls.items():
        o = run([l])
        if o: out += o
groups = dict(re.findall(r"^attributes #(\d+) = \{ (.*) \}$", out, re.M))
rows = []
for m in re.finditer(r"^declare (.*?)@(llvm\.[\w.$-]+)\((.*)\)(.*)$", out, re.M):
    pre, name, params, post = m.groups()
    # return attrs: tokens between declare and the return type are hard to split generically; take the
    # text before the type by re-parsing in Goose: we store the whole prefix and let the parser skip the type.
    fn = ""
    g = re.search(r"#(\d+)", post)
    if g: fn = groups[g.group(1)]
    if "goose-probe" in fn or "goose-probe" in post: continue
    rows.append((name, pre.strip(), params, fn))
rows.sort()
def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')
lines = ["// Generated by tools/gen_intrinsics.py (attributes of intrinsic declarations, from opt). Do not edit.",
         "// Each entry: name, '\\t', declaration prefix (return attrs + type), '\\t', parameter list, '\\t', fn attrs."]
lines.append("let INTRINSIC_ATTRS: const u8[:][] = [")
for name, pre, params, fn in rows:
    lines.append(f'    "{esc(name)}\\t{esc(pre)}\\t{esc(params)}\\t{esc(fn)}",')
lines.append("];")
open(os.path.join(ROOT, "impl/goose/src/gen_intrinsics.goose"), "w").write("\n".join(lines) + "\n")
print(len(rows), "intrinsics")
