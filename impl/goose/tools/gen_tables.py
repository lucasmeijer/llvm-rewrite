#!/usr/bin/env python3
"""Generates src/gen_attrs.goose: LLVM's Attribute::AttrKind enum (order and spelling) from Attributes.td,
and the fixed metadata kinds from FixedMetadataKinds.def.

The enum order is what AttributeImpl::cmp sorts by, so it decides the printed order of attributes.
Order (utils/TableGen/Basic/Attributes.cpp): EnumAttr, TypeAttr, IntAttr, ConstantRangeAttr,
ConstantRangeListAttr; within a class, records sorted by def name (RecordKeeper keeps a std::map).
"""
import re, sys
TD = "/opt/llvm-project-23.1.5/llvm/include/llvm/IR/Attributes.td"
src = open(TD).read()
src = re.sub(r"//[^\n]*", "", src)
classes = ["EnumAttr", "TypeAttr", "IntAttr", "ConstantRangeAttr", "ConstantRangeListAttr"]
defs = {c: [] for c in classes}
inter = {}
for m in re.finditer(r"\bdef\s+(\w+)\s*:\s*(\w+)\s*<\s*\"([^\"]*)\"\s*,\s*(\w+)", src):
    name, cls, s, prop = m.groups()
    if cls in defs:
        defs[cls].append((name, s))
        inter[name] = prop
out = ["// Generated by tools/gen_attrs.py from llvm/include/llvm/IR/Attributes.td. Do not edit.",
       "// Attribute kinds in LLVM's Attribute::AttrKind order (1-based; 0 = none).", ""]
names = []
cls_of = []
for ci, c in enumerate(classes):
    for name, s in sorted(defs[c]):
        names.append((name, s)); cls_of.append(ci)
out.append("let ATTR_CLASS_ENUM = 0;\nlet ATTR_CLASS_TYPE = 1;\nlet ATTR_CLASS_INT = 2;\nlet ATTR_CLASS_CRANGE = 3;\nlet ATTR_CLASS_CRANGELIST = 4;")
for i, (name, s) in enumerate(names):
    out.append(f"let AK_{name} = {i+1};")
out.append(f"let AK_COUNT = {len(names)+1};")
out.append("let ATTR_NAMES: const u8[:][] = [\"\", " + ", ".join(f'"{s}"' for _, s in names) + "];")
IK = {"IntersectPreserve": 0, "IntersectAnd": 1, "IntersectMin": 2, "IntersectCustom": 3}
out.append("// Intersection rule (Attributes.td): 0 IntersectPreserve, 1 IntersectAnd, 2 IntersectMin, 3 IntersectCustom")
out.append("let ATTR_INTERSECT: u8[] = [0, " + ", ".join(str(IK[inter[n]]) for n, _ in names) + "];")
out.append("let ATTR_CLASSES: u8[] = [0, " + ", ".join(str(c) for c in cls_of) + "];")
md = open("/opt/llvm-project-23.1.5/llvm/include/llvm/IR/FixedMetadataKinds.def").read()
kinds = sorted((int(n), s) for s, n in re.findall(r'LLVM_FIXED_MD_KIND\(\s*MD_\w+\s*,\s*"([^"]*)"\s*,\s*(\d+)\s*\)', md))
assert [n for n, _ in kinds] == list(range(len(kinds))), kinds
out.append("let FIXED_MD_KINDS: const u8[:][] = [" + ", ".join(f'"{s}"' for _, s in kinds) + "];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gen_attrs.goose", "w").write("\n".join(out) + "\n")
print(len(names), "attributes")
